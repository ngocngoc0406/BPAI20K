"""Near-Miss Memory: persistent local store of safety events extracted from analysis results.

Event types (fixed rules; no parameter was tuned on any test data):
  alert                 an alarm onset of the pipeline (profile threshold, k consecutive steps). Episode = onset .. last
                        consecutive step with P >= CAUTION threshold.
  near_miss_candidate   a run of >= k steps with calibrated P >= the CAUTION threshold (the 20 FA/h level on dev streams)
                        that did NOT produce an alarm. By construction its rate on normal driving is bounded by that budget.
Each event stores what the system measured: time span, peak probability and level, uncertainty, the grounded triggering cues and
explanation at the peak, the largest road user at the peak, model / profile, and an annotated clip (-3 s .. +1 s around the peak)
when frames are available. Nothing is generated by a language model.

Storage: data/memory/events.jsonl (one JSON object per line) and data/memory/clips/<event_id>.mp4.
"""
from __future__ import annotations

import json
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path

import numpy as np

from src.detection.detector import COCO_ROAD
from src.utils.config import resolve

MEMORY_DIR = resolve("data/memory")
CLIP_BEFORE_S, CLIP_AFTER_S = 3.0, 1.0


@dataclass
class SafetyEvent:
    event_id: str
    trip_id: str
    video: str
    model: str
    profile: str
    type: str                    # alert | near_miss_candidate
    t_start: float
    t_end: float
    t_peak: float
    p_peak: float
    level_peak: str
    risk_score_peak: float
    mutual_info_mean: float
    factors: list[dict]
    explanation: str
    lead_object: dict | None
    clip: str | None = None
    created: str = field(default_factory=lambda: datetime.now().isoformat(timespec="seconds"))
    note: str = ""

    def to_dict(self) -> dict:
        return asdict(self)


def _runs(mask: np.ndarray) -> list[tuple[int, int]]:
    out, start = [], None
    for i, m in enumerate(mask):
        if m and start is None:
            start = i
        if not m and start is not None:
            out.append((start, i - 1))
            start = None
    if start is not None:
        out.append((start, len(mask) - 1))
    return out


def _lead_object(res, step: int) -> dict | None:
    rows = res.features.tracks[res.features.tracks[:, 0] == step] if len(res.features.tracks) else np.zeros((0, 8))
    if len(rows) == 0:
        return None
    area = (rows[:, 6] - rows[:, 4]) * (rows[:, 7] - rows[:, 5])
    r = rows[int(np.argmax(area))]
    return {"track_id": int(r[1]), "class": COCO_ROAD.get(int(r[2]), str(int(r[2]))), "confidence": float(r[3]),
            "box": [float(x) for x in r[4:8]], "area_fraction": float(area.max())}


def extract_events(res, caution: float, trip_id: str = "", k: int = 3, warmup: float = 1.0, signal: str = "p_mean") -> list[SafetyEvent]:
    """res: AnalysisResult. caution: CAUTION threshold on calibrated probability (bundle risk.caution).
    warmup: no event before one full observation window (same rule as alarms)."""
    tl = res.timeline
    if len(tl) == 0:
        return []
    t = tl.time_s.to_numpy()
    p = tl[signal].to_numpy()  # 'p_mean' (v3: levels on calibrated probability) or 'risk_score' (v1 / v2)
    above = (p >= caution) & (t >= warmup - 1e-6)
    events: list[SafetyEvent] = []
    used = np.zeros(len(t), bool)
    model = Path(res.model_dir).name if res.model_dir else ""

    def make(kind: str, a: int, b: int) -> SafetyEvent:
        j = a + int(np.argmax(p[a:b + 1]))
        ass = res.assessments[j]
        return SafetyEvent(uuid.uuid4().hex[:12], trip_id, Path(res.video_path).name, model, getattr(res, "profile", "balanced"), kind,
                           float(t[a]), float(t[b]), float(t[j]), float(tl.p_mean.iloc[j]), str(tl.level.iloc[j]), float(tl.risk_score.iloc[j]),
                           float(tl.mutual_info.iloc[a:b + 1].mean()), ass.triggering_factors, ass.explanation,
                           _lead_object(res, int(tl.step.iloc[j])))

    for onset in res.alarms:
        a = int(np.searchsorted(t, onset - 1e-6))
        b = a
        while b + 1 < len(t) and above[b + 1]:
            b += 1
        used[a:b + 1] = True
        events.append(make("alert", a, b))
    for a, b in _runs(above):
        if b - a + 1 >= k and not used[a:b + 1].any():
            events.append(make("near_miss_candidate", a, b))
    return sorted(events, key=lambda e: e.t_start)


class NearMissMemory:
    def __init__(self, root: str | Path = MEMORY_DIR):
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)
        (self.root / "clips").mkdir(exist_ok=True)
        self.path = self.root / "events.jsonl"

    def add(self, events: list[SafetyEvent], res=None, save_clips: bool = True) -> list[SafetyEvent]:
        if save_clips and res is not None and res.frames:
            from src.visualization.overlay import draw_frame, write_video
            fps = res.features.fps
            tl = res.timeline
            for e in events:
                s0 = max(int((e.t_peak - CLIP_BEFORE_S) * fps), 0)
                s1 = min(int((e.t_peak + CLIP_AFTER_S) * fps), len(res.frames) - 1)
                frames = []
                for s in range(s0, s1 + 1):
                    rows = res.features.tracks[res.features.tracks[:, 0] == s]
                    j = max(int((tl.step <= s).sum()) - 1, 0)
                    r = tl.iloc[j]
                    frames.append(draw_frame(res.frames[s], rows, r.level, r.risk_score, r.p_mean, float(res.features.times[s])))
                if frames:
                    e.clip = str(write_video(frames, self.root / "clips" / f"{e.event_id}.mp4", fps))
        with open(self.path, "a", encoding="utf-8") as fh:
            for e in events:
                fh.write(json.dumps(e.to_dict(), ensure_ascii=False) + "\n")
        return events

    def all(self) -> list[dict]:
        if not self.path.exists():
            return []
        with open(self.path, encoding="utf-8") as fh:
            return [json.loads(line) for line in fh if line.strip()]

    def trips(self) -> list[str]:
        return sorted({e["trip_id"] for e in self.all() if e.get("trip_id")})

    def by_trip(self, trip_id: str) -> list[dict]:
        return [e for e in self.all() if e.get("trip_id") == trip_id]

    def update(self, event_id: str, **fields) -> bool:
        ev = self.all()
        hit = False
        for e in ev:
            if e["event_id"] == event_id:
                e.update(fields)
                hit = True
        if hit:
            with open(self.path, "w", encoding="utf-8") as fh:
                for e in ev:
                    fh.write(json.dumps(e, ensure_ascii=False) + "\n")
        return hit

    def confirm_collision(self, event_id: str, evidence: str) -> bool:
        """Manual only: a user with evidence (e.g. police / insurance record, visible contact) marks an event as a collision."""
        if not evidence or len(evidence.strip()) < 5:
            raise ValueError("Evidence note required to confirm a collision.")
        from datetime import datetime as _dt
        return self.update(event_id, category="confirmed_collision", type="confirmed_collision",
                           confirmed_evidence=evidence.strip(), confirmed_at=_dt.now().isoformat(timespec="seconds"))

    def delete(self, event_id: str) -> bool:
        ev = self.all()
        keep = [e for e in ev if e["event_id"] != event_id]
        if len(keep) == len(ev):
            return False
        for e in ev:
            if e["event_id"] == event_id and e.get("clip") and Path(e["clip"]).exists():
                Path(e["clip"]).unlink()
        with open(self.path, "w", encoding="utf-8") as fh:
            for e in keep:
                fh.write(json.dumps(e, ensure_ascii=False) + "\n")
        return True
