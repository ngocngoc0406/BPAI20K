"""Explainable AI.
v1 (neural, ResNet):  Grad-CAM + Integrated Gradients (temporal / motion) + grounded factors + permutation importance.
v2-light (tabular):  frame-change heatmap with tracked boxes + exact occlusion attributions per cue and per time step
                     + grounded factors + permutation importance.  Nothing is generated by a language model."""
from __future__ import annotations

import cv2
import numpy as np
import plotly.graph_objects as go
import streamlit as st

from src.features.frame_diff import FRAME_DIFF_FEATURES
from src.features.motion_features import FEATURE_DESCRIPTIONS
from src.risk.risk_engine import LEVEL_COLORS
from src.visualization.overlay import draw_frame
from ui.common import PLOT_LAYOUT, card, get_pipeline, pill, require_result, results, results_light, setup

setup("Explainable AI", "🧠")
st.title("🧠 Explainable AI")
res = require_result()
pipe = get_pipeline(res.model_dir or None)  # always explain with the model that produced the result
pred = pipe.predictor
tl = res.timeline
f = res.features

default = res.alarms[0] if res.alarms else float(tl.time_s.iloc[int(tl.risk_score.to_numpy().argmax())])
times = tl.time_s.to_numpy()
j_sel = st.select_slider("Explain the prediction at time (s)", options=list(range(len(tl))),
                         value=int(np.abs(times - default).argmin()), format_func=lambda j: f"{times[j]:.1f}")
row = tl.iloc[int(j_sel)]
i = int(row.step)
c = st.columns(4)
card(c[0], "Level", pill(row.level))
card(c[1], "P(collision)", f"{row.p_mean:.2f}")
card(c[2], "Risk score", f"{row.risk_score:.2f}")
card(c[3], "Ensemble disagreement (MI)", f"{row.mutual_info:.3f}")
st.write("")
a = res.assessments[int(np.argmin(np.abs(tl.time_s.to_numpy() - row.time_s)))]
from src.features.relational import FEATURE_DESCRIPTIONS_REL  # noqa: E402

_MODE = {"h": "camera-compensated (homography)", "f": "camera-compensated (flow)", "none": "uncompensated"}
DESC = {**FEATURE_DESCRIPTIONS, **{n: f"frame change ({n.replace('diff_', '')})" for n in FRAME_DIFF_FEATURES},
        "vis_change_norm": "CNN appearance change (norm)", "vis_change_cos": "CNN appearance change (cosine)",
        **{f"{n}@{m}": f"{d} [{_MODE[m]}]" for n, d in FEATURE_DESCRIPTIONS_REL.items() for m in _MODE},
        "egoh_dx": "camera pan (horizontal image motion)", "egoh_dy": "camera tilt / pitch (vertical image motion)",
        "egoh_zoom": "camera forward motion (image expansion)", "egoh_rot": "camera roll / rotation",
        "egoh_inliers": "camera-motion estimate quality (inlier ratio)", "egoh_reproj": "camera-motion residual (non-rigid / shake)",
        "egof_dx": "camera pan (flow)", "egof_dy": "camera tilt (flow)", "egof_zoom": "camera forward motion (flow)", "egof_rot": "camera rotation (flow)"}


def factors_panel():
    st.subheader("Why this warning? (grounded factors)")
    st.markdown(f'<div class="sd-card" style="border-color:{LEVEL_COLORS[a.level]}">{a.explanation}</div>', unsafe_allow_html=True)
    st.write("")
    if a.triggering_factors:
        for fc in a.triggering_factors:
            st.markdown(f"- **{fc['description']}**: {fc['value']:.3g} (typical {fc['typical']:.3g}, {fc['strength']:.1f} σ above typical)")
    else:
        st.caption("No motion cue is unusual at this moment (factors are shown only when a cue exceeds its training-set 90th percentile).")


if getattr(pred, "kind", "neural") == "tabular":
    @st.cache_data(show_spinner="Computing occlusion attributions…", max_entries=64)
    def explain_tab(model_dir: str, video: str, step: int):
        return pred.channel_contributions(f, float(f.times[step])), pred.temporal_contributions(f, float(f.times[step]))

    contrib, (tt, tc) = explain_tab(res.model_dir, res.video_path, i)
    left, right = st.columns([3, 2])
    with left:
        st.subheader("Where the scene changed + tracked road users")
        frame = res.frames[i]
        prev = res.frames[max(i - 1, 0)]
        d = cv2.absdiff(cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY), cv2.cvtColor(prev, cv2.COLOR_BGR2GRAY))
        d = cv2.GaussianBlur(d, (0, 0), 3).astype(np.float32)
        d = d / d.max() if d.max() > 0 else d
        heat = cv2.applyColorMap((d * 255).astype(np.uint8), cv2.COLORMAP_INFERNO)
        img = cv2.addWeighted(draw_frame(frame, f.tracks[f.tracks[:, 0] == i]), 0.6, heat, 0.4, 0)
        st.image(cv2.cvtColor(img, cv2.COLOR_BGR2RGB), use_container_width=True)
        st.caption("Input evidence, not a gradient saliency map: |frame t − frame t−1| (the same signal the model's frame-difference "
                   "features summarise), with the detector/tracker boxes the motion cues are computed from.")
    with right:
        factors_panel()
        grp = {"Object motion cues": 0.0, "Interactions (compensated)": 0.0, "Camera motion": 0.0, "Frame / appearance change": 0.0}
        for kk, vv in contrib.items():
            g_ = ("Object motion cues" if kk in FEATURE_DESCRIPTIONS else "Interactions (compensated)" if "@" in kk
                  else "Camera motion" if kk.startswith("ego") else "Frame / appearance change")
            grp[g_] += abs(vv)
        grp = {k_: v_ for k_, v_ in grp.items() if v_ > 0}
        fig = go.Figure(go.Pie(labels=list(grp), values=list(grp.values()), hole=.55,
                               marker_colors=["#f97316", "#eab308", "#a855f7", "#22d3ee"][: len(grp)]))
        fig.update_layout(**PLOT_LAYOUT, height=260, title="Attribution share (|occlusion Δp|)")
        st.plotly_chart(fig, use_container_width=True)
    c1, c2 = st.columns(2)
    with c1:
        fig = go.Figure(go.Bar(x=tt, y=tc, marker_color=["#ef4444" if v > 0 else "#22c55e" for v in tc]))
        fig.update_layout(**PLOT_LAYOUT, height=300, title="Temporal contribution — Δp if that frame brought no new information",
                          xaxis_title="time (s)", yaxis_title="Δ P(collision)")
        st.plotly_chart(fig, use_container_width=True)
    with c2:
        top = sorted(contrib.items(), key=lambda kv: -abs(kv[1]))[:10][::-1]
        fig = go.Figure(go.Bar(y=[DESC.get(k, k)[:48] for k, _ in top], x=[v for _, v in top], orientation="h",
                               marker_color=["#ef4444" if v > 0 else "#22c55e" for _, v in top]))
        fig.update_layout(**PLOT_LAYOUT, height=300, title="Cue contribution (occlusion to training median; red = toward collision)")
        st.plotly_chart(fig, use_container_width=True)
    rl = results_light()
    imp = rl.get("permutation_importance_test_ap_drop") if rl else None
    method_note = "occlusion attributions (exact for this model), frame-change evidence, permutation importance"
else:
    from src.explainability.attribution import group_contributions, integrated_gradients
    from src.explainability.gradcam import GradCAM, overlay_cam
    V, M = pred.windows_for(f, np.array([f.times[i]]))

    @st.cache_data(show_spinner="Computing Grad-CAM and Integrated Gradients…", max_entries=64)
    def explain_nn(model_dir: str, video: str, step: int):
        ig = integrated_gradients(pred.models, V[0], M[0], pipe.device, steps=32)
        cam = GradCAM(pred, pipe.device)(res.frames[step], V[0], M[0])
        return ig, cam

    ig, cam = explain_nn(res.model_dir, res.video_path, i)
    left, right = st.columns([3, 2])
    with left:
        st.subheader("Grad-CAM — where the model looked (last frame of window)")
        st.image(overlay_cam(res.frames[i], cam), use_container_width=True)
        st.caption("Gradient of the ensemble collision logit back-propagated through the temporal model into ResNet-18 layer4.")
    with right:
        factors_panel()
        gc = group_contributions(ig)
        fig = go.Figure(go.Pie(labels=["Visual appearance (CNN)", "Motion cues"], values=[gc["visual"], gc["motion"]], hole=.55,
                               marker_colors=["#22d3ee", "#f97316"]))
        fig.update_layout(**PLOT_LAYOUT, height=260, title="Attribution share (|IG|)")
        st.plotly_chart(fig, use_container_width=True)
    c1, c2 = st.columns(2)
    with c1:
        ts = f.times[max(i - len(ig["temporal"]) + 1, 0): i + 1]
        fig = go.Figure(go.Bar(x=ts, y=ig["temporal"][-len(ts):], marker_color="#22d3ee"))
        fig.update_layout(**PLOT_LAYOUT, height=300, title="Temporal attribution — which moments mattered",
                          xaxis_title="time (s)", yaxis_title="|IG| summed over features")
        st.plotly_chart(fig, use_container_width=True)
    with c2:
        top = sorted(ig["motion_by_feature"].items(), key=lambda kv: -abs(kv[1]))[:10][::-1]
        fig = go.Figure(go.Bar(y=[FEATURE_DESCRIPTIONS[k][:48] for k, _ in top], x=[v for _, v in top], orientation="h",
                               marker_color=["#ef4444" if v > 0 else "#22c55e" for _, v in top]))
        fig.update_layout(**PLOT_LAYOUT, height=300, title="Motion contribution (IG; red = pushes toward collision)")
        st.plotly_chart(fig, use_container_width=True)
    r = results()
    imp = r.get("permutation_importance_test_ap_drop") if r else None
    method_note = "Grad-CAM, Integrated Gradients, permutation importance"

if imp:
    st.subheader("Global feature importance (test set, permutation)")
    pi = list(imp.items())[:12][::-1]
    fig = go.Figure(go.Bar(y=[DESC.get(k, k)[:48] for k, _ in pi], x=[v for _, v in pi], orientation="h", marker_color="#a855f7"))
    fig.update_layout(**PLOT_LAYOUT, height=380, xaxis_title="drop in average precision when the feature is shuffled")
    st.plotly_chart(fig, use_container_width=True)
st.caption(f"Explanations come only from implemented methods ({method_note}) and measured motion cues. "
           "No language model generates reasons.")
