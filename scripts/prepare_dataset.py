"""Locate Nexar metadata, canonicalise annotations, validate videos, split by video, compute statistics.

Outputs: data/annotations/nexar_train.csv, data/processed/splits.json, data/processed/dataset_stats.json,
         data/processed/validation.json
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from src.data.annotation_parser import parse_annotations  # noqa: E402
from src.data.dataset_loader import load_dataset, records_to_frame  # noqa: E402
from src.data.dataset_splitter import split_videos  # noqa: E402
from src.data.dataset_statistics import compute_statistics  # noqa: E402
from src.data.dataset_validator import validate  # noqa: E402
from src.utils.config import load_config, resolve  # noqa: E402
from src.utils.io import save_json  # noqa: E402
from src.utils.logging_utils import get_logger  # noqa: E402

log = get_logger("prepare", resolve("experiments/logs/prepare.log"))


def find_metadata(raw: Path) -> list[Path]:
    return sorted(p for p in raw.rglob("*.csv") if "sample_submission" not in p.name and "solution" not in p.name
                  and "test" not in p.name.lower())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=None)
    cfg = load_config(ap.parse_args().config)
    raw = resolve(cfg["paths"]["raw_dir"])
    metas = find_metadata(raw)
    if not metas:
        log.error("No train metadata CSV under %s - cannot obtain time_of_event; refusing to invent labels.", raw)
        return 2
    frames = []
    for m in metas:
        try:
            df = parse_annotations(m)
            log.info("parsed %s: %d rows, columns=%s", m, len(df), list(pd.read_csv(m, nrows=1).columns))
            frames.append(df)
        except Exception as e:  # noqa: BLE001
            log.warning("skip %s: %s", m, e)
    ann = pd.concat(frames).drop_duplicates("video_id")
    out_ann = resolve(cfg["paths"]["annotations"])
    out_ann.parent.mkdir(parents=True, exist_ok=True)
    ann.to_csv(out_ann, index=False)
    recs = load_dataset(out_ann, raw)
    log.info("annotated: %d, with local video: %d", len(ann), len(recs))
    rep = validate(recs, probe=True)
    log.info("validation: %d ok, %d with issues", len(rep.ok), rep.n_bad)
    good = [r for r in recs if r.video_id in set(rep.ok)]
    splits = split_videos(good, cfg["dataset"]["split"], cfg["seed"])
    save_json(splits, resolve(cfg["paths"]["splits"]))
    df = records_to_frame(good)
    stats = {"all": compute_statistics(df, rep.video_info)}
    for k, ids in splits.items():
        stats[k] = compute_statistics(df[df.video_id.isin(ids)])
    stats["annotation_columns"] = list(ann.columns)
    stats["annotation_rows_total"] = int(len(ann))
    save_json(stats, resolve("data/processed/dataset_stats.json"))
    save_json({"issues": rep.issues, "video_info": rep.video_info}, resolve("data/processed/validation.json"))
    log.info("splits: %s", {k: len(v) for k, v in splits.items()})
    write_report(stats, rep, splits, ann, len(recs), cfg)
    return 0


def write_report(stats: dict, rep, splits: dict, ann: pd.DataFrame, n_local: int, cfg: dict) -> None:
    a = stats["all"]

    def d(x: dict, p: int = 2) -> str:
        return f"mean {x['mean']:.{p}f} · median {x['median']:.{p}f} · min {x['min']:.{p}f} · max {x['max']:.{p}f}" if x else "—"

    full_pos = ann[ann.label == 1]
    lines = [
        "# Dataset Report — Nexar Dashcam Collision Prediction",
        "<!-- generated by scripts/prepare_dataset.py -->",
        "",
        "## Source, access, licence",
        f"- Hugging Face `{cfg['dataset']['hf_repo']}` (gated; access granted to the user's account), from the Nexar challenge "
        "(Moura, Zhu, Zvitia, CVPR-W 2025, arXiv 2503.03848).",
        "- Licence: **Nexar Open Data License**. Free use with attribution; no resale, no re-identification of people or "
        "vehicles, no use in harmful systems. Videos are not redistributed with this project.",
        "",
        "## Structure (verified)",
        "- `train/positive/*.mp4` + `train/positive/metadata.csv`; `train/negative/*.mp4` + `train/negative/metadata.csv`.",
        "- Raw metadata columns: file_name, time_of_event, time_of_alert, light_conditions, weather, scene, time_to_accident "
        f"(canonicalised to: {', '.join(stats['annotation_columns'])}). There is **no label column**: the class is "
        "defined by the folder (positive = collision or near-collision, negative = normal driving). `time_to_accident` is empty in train.",
        f"- Full train annotation: {len(ann)} rows ({int((ann.label == 1).sum())} positive / {int((ann.label == 0).sum())} negative). "
        f"Every positive has time_of_event: {bool(full_pos.time_of_event.notna().all())}; "
        f"time_of_alert ≤ time_of_event everywhere: {bool((full_pos.time_of_alert <= full_pos.time_of_event).all())}.",
        "- Collision and near-collision are **not** distinguished by separate labels, so the task is binary.",
        "",
        "## Local subset",
        f"- Balanced random subset (seed {cfg['seed']}): {n_local} videos downloaded; {len(rep.ok)} passed validation, "
        f"{rep.n_bad} have issues: {rep.issues if rep.issues else 'none'}.",
        f"- Duration: {d(a.get('duration_s', {}), 1)} s. FPS: {a.get('fps')}. Resolution: {a.get('resolution')}.",
        f"- time_of_event: {d(a.get('time_of_event_s', {}))} s.",
        f"- time_of_alert: {d(a.get('time_of_alert_s', {}))} s.",
        f"- Alert lead (event − alert): {d(a.get('alert_lead_s', {}))} s.",
    ]
    for k in ("light_conditions", "weather", "scene"):
        if k in a:
            lines.append(f"- {k}: {a[k]}")
    lines += ["", "## Split (video-level, stratified, no leakage)", "| split | videos | positive | negative |", "|---|---|---|---|"]
    for k in ("train", "val", "test"):
        s = stats[k]
        lines.append(f"| {k} | {s['n_videos']} | {s['n_positive']} | {s['n_negative']} |")
    lines += ["", "Windows are cut only inside each split's own videos (see EXPERIMENT_DESIGN.md), and positive windows always "
              "end before time_of_event."]
    resolve("docs/DATASET_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    raise SystemExit(main())
